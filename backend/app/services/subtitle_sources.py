"""Public platform caption metadata adapters; consumed only through ytdlp_service."""
from __future__ import annotations

import json
import re
from urllib.parse import quote, unquote, urlparse

import httpx

from ..config import settings
from . import network_retry
from .bilibili_subtitle_source import InvalidVideoPartError, bilibili_tracks
from .bilibili_session import SessionError
from .outbound_httpx import ControlledHttpError
from .outbound_policy import OutboundError, OutboundPurpose, OutboundUnavailableError
from .source_network import current_source_network

_CAPTION_FORMATS = {"srt", "vtt", "json3", "ttml", "srv3"}
_LANGUAGE_ALIASES = {
    "eng": "en", "english": "en", "fra": "fr", "fre": "fr", "french": "fr",
    "zho": "zh", "chi": "zh", "chinese": "zh", "jpn": "ja", "japanese": "ja",
}
_CAPTION_LANGUAGE_TAGS = {
    "en", "fr", "zh", "ja", "ko", "de", "es", "pt", "it", "ru", "ar", "hi",
    "nl", "tr", "vi", "pl", "uk", "sv", "fi", "da", "no", "he", "id", "th", "und",
}
_AUTO_TAGS = {"asr", "auto", "autogenerated"}


def _language(value) -> str:
    if not isinstance(value, str):
        return "und"
    value = value.strip().lower()
    value = _LANGUAGE_ALIASES.get(value, value)
    return value if re.fullmatch(r"[a-z]{2,3}(?:-[a-z0-9]{2,8})*", value) else "und"


def _caption_identity(name: str, default_language: str) -> tuple[str, str, bool]:
    # Strip only recognized caption suffixes, preserving part numbers and ordinary stem tokens.
    tokens = name.rsplit(".", 1)[0].split(".")
    language = None
    is_auto = False
    while len(tokens) > 1:
        tag = tokens[-1].lower()
        if tag in _AUTO_TAGS:
            is_auto = True
            tokens.pop()
        elif language is None and _language(tag).split("-", 1)[0] in _CAPTION_LANGUAGE_TAGS:
            language = _language(tag)
            tokens.pop()
        else:
            break
    return ".".join(tokens), language or default_language, is_auto


def _archive_tracks(url: str) -> dict:
    parts = urlparse(url).path.strip("/").split("/")
    if len(parts) < 2 or parts[0] not in {"details", "download"}:
        return {"tracks": []}
    identifier = unquote(parts[1])
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", identifier) or identifier in {".", ".."}:
        return {"tracks": []}
    metadata_url = f"https://archive.org/metadata/{quote(identifier, safe='')}"
    network = current_source_network()
    if network is not None:
        with network.stream(metadata_url, purpose=OutboundPurpose.METADATA,
                max_bytes=settings.subtitle_max_bytes, phase_seconds=settings.subtitle_timeout_seconds,
                io_timeout=settings.subtitle_timeout_seconds) as response:
            response.raise_for_status()
            body = response.read()
    else:
        body = _archive_metadata(metadata_url)
    data = json.loads(body)
    return _archive_payload(data, identifier, parts)


def _archive_metadata(metadata_url: str) -> bytes:
    with httpx.Client(timeout=settings.subtitle_timeout_seconds, follow_redirects=True) as client:
        def get_metadata() -> bytes:
            with client.stream("GET", metadata_url) as response:
                response.raise_for_status()
                body = bytearray()
                for chunk in response.iter_bytes():
                    if len(body) + len(chunk) > settings.subtitle_max_bytes:
                        raise ValueError("字幕来源元数据超过大小限制")
                    body.extend(chunk)
                return bytes(body)

        body = network_retry.retry_get(
            get_metadata,
            max_retries=settings.network_retries,
            backoff_seconds=settings.network_retry_backoff_seconds,
        )
    return body


def _archive_payload(data, identifier: str, parts: list[str]) -> dict:
    if not isinstance(data, dict) or data.get("is_dark"):
        return {"tracks": []}
    metadata = data.get("metadata", {})
    files = data.get("files", [])
    if not isinstance(metadata, dict) or not isinstance(files, list) or any(not isinstance(file, dict) for file in files):
        raise ValueError("字幕来源元数据结构无效")
    title = metadata.get("title") or ""
    if not isinstance(title, str):
        raise ValueError("字幕来源标题格式无效")
    declared_language = metadata.get("language")
    if isinstance(declared_language, list):
        declared_language = declared_language[0] if len(declared_language) == 1 else None
    default_language = _language(declared_language)
    # A file-specific video URL must not pick captions belonging to another video in the item.
    selected_file = unquote("/".join(parts[2:]))
    selected_stem = selected_file.rsplit(".", 1)[0] if selected_file else None
    groups: dict[tuple[str, bool], dict] = {}
    caption_stems: set[str] = set()
    for file in files:
        name = file.get("name", "")
        if not isinstance(name, str) or file.get("private") in (True, 1, "true", "1"):
            continue
        ext = name.rsplit(".", 1)[-1].lower()
        if ext not in _CAPTION_FORMATS:
            continue
        caption_stem, language, is_auto = _caption_identity(name, default_language)
        if selected_stem and caption_stem != selected_stem:
            continue
        caption_stems.add(caption_stem)
        group = groups.setdefault((language, is_auto), {"language": language, "is_auto": is_auto, "formats": []})
        group["formats"].append({
            "url": f"https://archive.org/download/{quote(identifier, safe='')}/{quote(name, safe='/')}",
            "ext": ext, "name": name, "http_headers": {},
        })
    if not selected_file and len(caption_stems) > 1:
        raise ValueError("该条目包含多个视频内容，请提供具体视频文件链接")
    return {"title": title, "tracks": list(groups.values())}


# New public-platform fallbacks register here; routes and summary services stay platform-neutral.
_ADAPTERS = {"archive.org": _archive_tracks, "www.archive.org": _archive_tracks,
             "bilibili.com": bilibili_tracks, "www.bilibili.com": bilibili_tracks}


def resolve_public_subtitles(url: str) -> dict:
    parsed = urlparse(url)
    adapter = _ADAPTERS.get(parsed.hostname or "") if parsed.scheme in {"http", "https"} else None
    if current_source_network() is None:
        return adapter(url) if adapter else {"tracks": []}
    # Until the yt-dlp owner installs its guarded handler, an empty public
    # result or legacy parsing/network error must not enter that fallback.
    try:
        result = adapter(url) if adapter else {"tracks": []}
        if result.get('tracks'):
            return result
    except (OutboundError, ControlledHttpError, InvalidVideoPartError, SessionError):
        raise
    except (httpx.HTTPError, ValueError, TypeError):
        pass
    # Raise outside the except suite; raw source errors must not be retained.
    raise OutboundUnavailableError() from None
