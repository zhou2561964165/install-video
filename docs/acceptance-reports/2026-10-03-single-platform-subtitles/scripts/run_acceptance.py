"""Run a small, public Internet Archive subtitle acceptance sample.

The app config is stubbed before imports so this harness never reads backend/.env.
It calls the repository's real yt-dlp subtitle-track and subtitle parsing services.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
import time
import types
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import quote, urlsplit
from types import SimpleNamespace

import httpx


REPORT_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = REPORT_DIR.parents[2]
MAX_TEST_BYTES = 32 * 1024 * 1024

# First sample closes the platform → track → HTTP → parser path before expansion.
SAMPLES = [
    {
        "sample_id": "IA-lca2019-Awesome_Monitoring_Infrastructure_Using_the_Elastic_Stack-eng-vtt",
        "identifier": "lca2019-Awesome_Monitoring_Infrastructure_Using_the_Elastic_Stack",
        "language": "en",
        "format": "vtt",
        "file_name": "Awesome_Monitoring_Infrastructure_Using_the_Elastic_Stack.autogenerated.vtt",
    },
]

ALLOWED_LICENSE_RE = re.compile(
    r"^https?://creativecommons\.org/(?:licenses/by(?:-sa)?/[0-9.]+/?|publicdomain/(?:zero|mark)/[0-9.]+/?)$",
    re.IGNORECASE,
)
TIMESTAMP_RE = re.compile(
    r"(?m)^\s*(\d{2,}:\d{2}:\d{2}[.,]\d{3}|\d{2}:\d{2}[.,]\d{3})"
    r"\s*-->\s*(\d{2,}:\d{2}:\d{2}[.,]\d{3}|\d{2}:\d{2}[.,]\d{3})"
)
EMAIL_RE = re.compile(r"(?i)\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b")
PHONE_RE = re.compile(r"(?<!\w)(?:\+?\d[\d .()/-]{7,}\d)(?!\w)")


def import_app_services_without_dotenv():
    sys.path.insert(0, str(REPO_ROOT / "backend"))
    config = types.ModuleType("app.config")
    config.settings = SimpleNamespace(
        ffmpeg_path="ffmpeg",
        subtitle_max_bytes=MAX_TEST_BYTES,
    )
    sys.modules["app.config"] = config
    from app.services import subtitle_service, ytdlp_service

    return subtitle_service, ytdlp_service


def parse_time(value: str) -> float:
    value = value.replace(",", ".")
    pieces = value.split(":")
    if len(pieces) == 2:
        hours = 0
        minutes, seconds = pieces
    else:
        hours = int(pieces[-3])
        minutes, seconds = pieces[-2:]
    whole, millis = seconds.split(".")
    return hours * 3600 + int(minutes) * 60 + int(whole) + int(millis) / 1000


def audit_timeline(raw_text: str) -> dict:
    intervals = []
    for start_text, end_text in TIMESTAMP_RE.findall(raw_text):
        start, end = parse_time(start_text), parse_time(end_text)
        intervals.append((start, end))
    reversed_count = sum(start > end for start, end in intervals)
    source_ordered = all(
        intervals[index][0] <= intervals[index + 1][0]
        for index in range(len(intervals) - 1)
    )
    overlap_count = 0
    max_end = float("-inf")
    for start, end in intervals:
        if start < max_end:
            overlap_count += 1
        max_end = max(max_end, end)
    return {
        "cue_count": len(intervals),
        "intervals_finite": all(map(lambda pair: all(map(lambda n: n == n and abs(n) != float("inf"), pair)), intervals)),
        "reversed_interval_count": reversed_count,
        "source_start_ordered": source_ordered if intervals else None,
        "overlap_count": overlap_count,
        "first_start_seconds": intervals[0][0] if intervals else None,
        "last_end_seconds": intervals[-1][1] if intervals else None,
    }


def sanitize(text: str) -> tuple[str, dict]:
    text, emails = EMAIL_RE.subn("[EMAIL REDACTED]", text)
    text, phones = PHONE_RE.subn("[PHONE REDACTED]", text)
    return text, {"emails_redacted": emails, "phone_like_strings_redacted": phones}


def read_json(path: Path, default: dict) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def run_sample(spec: dict, subtitle_service, ytdlp_service) -> tuple[dict, dict]:
    overall_started = time.perf_counter()
    item_url = f"https://archive.org/details/{spec['identifier']}"
    metadata_started = time.perf_counter()
    metadata_response = httpx.get(
        f"https://archive.org/metadata/{spec['identifier']}", timeout=30.0, follow_redirects=True
    )
    metadata_response.raise_for_status()
    metadata_payload = metadata_response.json()
    metadata_ms = round((time.perf_counter() - metadata_started) * 1000, 1)
    item_metadata = metadata_payload.get("metadata", {})
    license_url = item_metadata.get("licenseurl") or ""
    if not ALLOWED_LICENSE_RE.fullmatch(license_url):
        raise ValueError("Item lacks an allowed explicit license URL")

    source_file = next(
        (f for f in metadata_payload.get("files", []) if f.get("name", "").casefold() == spec["file_name"].casefold()),
        None,
    )
    if not source_file:
        raise LookupError("Expected caption file is absent from item metadata")
    source_ext = Path(spec["file_name"]).suffix.lstrip(".").casefold()
    if source_ext not in {"vtt", "srt", "ttml", "xml", "ass", "ssa", "json3"}:
        raise ValueError("Unsupported caption file extension")

    license_metadata_path = REPORT_DIR / "raw" / f"{spec['sample_id']}.license-metadata.json"
    license_record = {
        "identifier": spec["identifier"],
        "title": item_metadata.get("title"),
        "creator": item_metadata.get("creator"),
        "licenseurl": license_url,
    }
    write_json(license_metadata_path, license_record)

    ytdlp_started = time.perf_counter()
    extracted = ytdlp_service.extract_subtitle_tracks(item_url)
    ytdlp_ms = round((time.perf_counter() - ytdlp_started) * 1000, 1)
    aliases = {"en": {"en", "eng", "english"}, "fr": {"fr", "fra", "fre", "french"}}
    wanted_languages = aliases.get(spec["language"].casefold(), {spec["language"].casefold()})
    candidates = [
        track for track in extracted["tracks"]
        if track["language"].casefold() in wanted_languages
        or track["language"].casefold().split("-", 1)[0] == spec["language"].casefold().split("-", 1)[0]
    ]
    track = candidates[0] if candidates else None
    formats = [fmt for fmt in (track["formats"] if track else []) if fmt["ext"].casefold() == spec["format"]]
    selected_format = formats[0] if formats else None
    acquisition_mode = "ytdlp_subtitle_track" if selected_format else "direct_item_file_metadata_fallback"
    if not selected_format:
        selected_format = {
            "url": f"https://archive.org/download/{spec['identifier']}/{quote(source_file['name'], safe='/')}",
            "http_headers": {},
            "ext": source_ext,
        }

    subtitle_started = time.perf_counter()
    response = httpx.get(
        selected_format["url"],
        headers=selected_format.get("http_headers") or {},
        timeout=30.0,
        follow_redirects=True,
    )
    response.raise_for_status()
    subtitle_http_ms = round((time.perf_counter() - subtitle_started) * 1000, 1)
    raw_bytes = response.content
    if len(raw_bytes) > MAX_TEST_BYTES:
        raise ValueError("Subtitle exceeds local test cap")
    raw_text = raw_bytes.decode(response.encoding or "utf-8", errors="replace")
    raw_path = REPORT_DIR / "raw" / f"{spec['sample_id']}.{selected_format['ext']}"
    raw_path.write_bytes(raw_bytes)
    content_sha256 = hashlib.sha256(raw_bytes).hexdigest()
    try:
        parsed_text = subtitle_service.parse_subtitle_text(raw_text, selected_format["ext"])
        parser_error = None
    except Exception as exc:
        parsed_text = ""
        parser_error = getattr(exc, "error_type", type(exc).__name__)

    # Exercise the repository's full platform → track → HTTP → parse path independently.
    service_error = None
    service_started = time.perf_counter()
    try:
        document = subtitle_service.fetch_subtitle_document(
            item_url, language=track["language"] if track else spec["language"]
        )
        service_matches = bool(parsed_text) and document.text == parsed_text
    except Exception as exc:
        service_matches = False
        service_error = getattr(exc, "error_type", type(exc).__name__)
    service_ms = round((time.perf_counter() - service_started) * 1000, 1)

    sanitized_text, redactions = sanitize(parsed_text)
    clean_path = REPORT_DIR / "sanitized" / f"{spec['sample_id']}.txt"
    clean_path.write_text(sanitized_text, encoding="utf-8")

    track_url = urlsplit(selected_format["url"])
    safe_track_url = f"{track_url.scheme}://{track_url.netloc}{track_url.path}"
    provenance_hint = "auto" if re.search(r"auto.?generated|\.asr\.|\.auto\.", source_file.get("name", ""), re.I) else "unknown"

    manifest = {
        "sample_id": spec["sample_id"],
        "platform": "Internet Archive",
        "source_id": spec["identifier"],
        "source_url": item_url,
        "track_url_without_query": safe_track_url,
        "captured_at_utc": datetime.now(timezone.utc).isoformat(),
        "license_url": license_url,
        "permission_basis": "Item-level Internet Archive licenseurl; item declares CC BY or CC BY-SA; attribution retained in metadata.",
        "original_format": selected_format["ext"],
        "source_file_name": source_file.get("name"),
        "archive_md5": source_file.get("md5"),
        "sha256": content_sha256,
        "bytes": len(raw_bytes),
        "language": track["language"] if track else spec["language"],
        "yt_dlp_track_found": track is not None,
        "yt_dlp_is_auto": track["is_auto"] if track else None,
        "caption_provenance": provenance_hint,
        "title": extracted.get("title"),
        "acquisition_mode": acquisition_mode,
        "raw_path": str(raw_path.relative_to(REPORT_DIR)).replace("\\", "/"),
        "license_metadata_path": str(license_metadata_path.relative_to(REPORT_DIR)).replace("\\", "/"),
        "sanitized_path": str(clean_path.relative_to(REPORT_DIR)).replace("\\", "/"),
    }
    result = {
        "sample_id": spec["sample_id"],
        "platform_integration_pass": service_matches,
        "platform_integration_error_type": service_error,
        "yt_dlp_tracks_returned": len(extracted["tracks"]),
        "matching_language_track_found": track is not None,
        "acquisition_mode": acquisition_mode,
        "parser_pass": bool(parsed_text.strip()),
        "parser_error_type": parser_error,
        "plain_text_nonempty": bool(parsed_text.strip()),
        "timestamps_or_cue_metadata_in_output": bool(TIMESTAMP_RE.search(parsed_text)),
        "unicode_replacement_characters": raw_text.count("\ufffd"),
        "text_characters": len(parsed_text),
        "timeline_audit": audit_timeline(raw_text),
        "timings_ms": {
            "item_metadata_http": metadata_ms,
            "yt_dlp_track_extraction": ytdlp_ms,
            "subtitle_file_http": subtitle_http_ms,
            "application_fetch_parse": service_ms,
            "total": round((time.perf_counter() - overall_started) * 1000, 1),
        },
        "redactions": redactions,
        "unmeasured": ["audio/text alignment", "speaker identity/turn accuracy", "background noise", "language and punctuation quality without human reference"],
        "evidence": {
            "raw_sha256": content_sha256,
            "raw_path": manifest["raw_path"],
            "sanitized_path": manifest["sanitized_path"],
        },
    }
    return manifest, result


def main() -> int:
    subtitle_service, ytdlp_service = import_app_services_without_dotenv()
    manifest_file = REPORT_DIR / "manifest.json"
    results_file = REPORT_DIR / "test-results.json"
    manifest_payload = read_json(manifest_file, {"platform": "Internet Archive", "samples": []})
    results_payload = read_json(results_file, {"platform": "Internet Archive", "samples": []})
    errors = []
    for spec in SAMPLES:
        try:
            manifest_entry, result_entry = run_sample(spec, subtitle_service, ytdlp_service)
            manifest_payload["samples"] = [
                sample for sample in manifest_payload["samples"] if sample["sample_id"] != spec["sample_id"]
            ] + [manifest_entry]
            results_payload["samples"] = [
                sample for sample in results_payload["samples"] if sample["sample_id"] != spec["sample_id"]
            ] + [result_entry]
        except Exception as exc:  # Keep the failure evidence without emitting URLs or caption content.
            errors.append({"sample_id": spec["sample_id"], "error_type": type(exc).__name__})
        write_json(manifest_file, manifest_payload)
        write_json(results_file, results_payload)
    errors_file = REPORT_DIR / "collection-errors.json"
    write_json(errors_file, {"attempts": errors})
    print(json.dumps({"sample_count": len(manifest_payload["samples"]), "results": results_payload["samples"], "errors": errors}, ensure_ascii=False, indent=2))
    return 0 if not errors else 1


if __name__ == "__main__":
    raise SystemExit(main())
