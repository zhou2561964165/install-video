def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def import_services():
    sys.path.insert(0, str(REPO_ROOT / "backend"))
    config = types.ModuleType("app.config")
    config.settings = SimpleNamespace(ffmpeg_path="ffmpeg", subtitle_max_bytes=MAX_TEST_BYTES)
    sys.modules["app.config"] = config
    from app.services import subtitle_service, ytdlp_service

    return subtitle_service, ytdlp_service


def parse_seconds(value: str) -> float:
    value = value.replace(",", ".")
    fields = value.split(":")
    if len(fields) == 2:
        hours = 0
        minutes, seconds = fields
    else:
        hours = int(fields[-3])
        minutes, seconds = fields[-2:]
    whole, fractional = seconds.split(".")
    millis = int(fractional.ljust(3, "0")[:3])
    return hours * 3600 + int(minutes) * 60 + int(whole) + millis / 1000


def audit_timeline(raw_text: str) -> dict:
    source_matches = SOURCE_TIMESTAMP_RE.findall(raw_text)
    intervals = [(parse_seconds(a), parse_seconds(b)) for a, b in source_matches]
    starts = [start for start, _ in intervals]
    regressions = sum(starts[index] > starts[index + 1] for index in range(len(starts) - 1))
    overlap_count = 0
    max_end = float("-inf")
    for start, end in intervals:
        if start < max_end:
            overlap_count += 1
        max_end = max(max_end, end)
    return {
        "cue_count": len(intervals),
        "nonstandard_fraction_precision_count": sum(
            len(re.split(r"[.,]", value)[-1]) != 3
            for pair in source_matches for value in pair
        ),
        "all_intervals_finite": all(math.isfinite(v) for pair in intervals for v in pair) if intervals else None,
        "start_after_end_count": sum(start > end for start, end in intervals),
        "source_start_order_regressions": regressions,
        "overlapping_cue_count": overlap_count,
        "first_start_seconds": intervals[0][0] if intervals else None,
        "last_end_seconds": intervals[-1][1] if intervals else None,
    }


def sanitize(text: str) -> tuple[str, dict]:
    text, emails = EMAIL_RE.subn("[EMAIL REDACTED]", text)
    text, phones = PHONE_RE.subn("[PHONE REDACTED]", text)
    return text, {"emails_redacted": emails, "phone_like_strings_redacted": phones}


def extract_source_body(raw_text: str) -> str:
    cues = []
    lines = raw_text.replace("\r\n", "\n").replace("\r", "\n").splitlines()
    index = 0
    while index < len(lines):
        if SOURCE_TIMESTAMP_RE.match(lines[index]):
            index += 1
            cue_lines = []
            while index < len(lines) and lines[index].strip():
                cue_lines.append(re.sub(r"<[^>]+>", "", html.unescape(lines[index])).strip())
                index += 1
            cue = re.sub(r"\s+", " ", " ".join(cue_lines)).strip()
            if cue and (not cues or cues[-1] != cue):
                cues.append(cue)
        index += 1
    return "\n".join(cues)


def main() -> int:
    subtitle_service, ytdlp_service = import_services()
    manifest_entries = []
    result_entries = []
    duplicate_hashes = {}
    source_body_hashes = {}
    for spec in SAMPLES:
        raw_path = REPORT_DIR / spec["raw_dir"] / spec["file_name"]
        receipt_path = REPORT_DIR / "licenses" / f"{spec['sample_id']}.capture.json"
        license_path = REPORT_DIR / "licenses" / f"{spec['sample_id']}.license-metadata.json"
        raw_bytes = raw_path.read_bytes()
        receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
        license_record = json.loads(license_path.read_text(encoding="utf-8"))
        raw_sha256 = hashlib.sha256(raw_bytes).hexdigest()
        byte_hash_matches_receipt = raw_sha256 == receipt["sha256"]
        utf8_strict = True
        try:
            raw_text = raw_bytes.decode("utf-8-sig", errors="strict")
            encoding = "utf-8-sig" if raw_bytes.startswith(b"\xef\xbb\xbf") else "utf-8"
        except UnicodeDecodeError:
            utf8_strict = False
            encoding = "response/default fallback not captured; decode error"
            raw_text = raw_bytes.decode("utf-8", errors="replace")
        ext = raw_path.suffix.lower().lstrip(".")
        parser_error = None
        try:
            parsed = subtitle_service.parse_subtitle_text(raw_text, ext)
        except Exception as exc:
            parsed = ""
            parser_error = getattr(exc, "error_type", type(exc).__name__)
        normalized_hash = hashlib.sha256(" ".join(parsed.casefold().split()).encode("utf-8")).hexdigest() if parsed else None
        duplicate_of = duplicate_hashes.get(normalized_hash) if normalized_hash else None
        if normalized_hash and not duplicate_of:
            duplicate_hashes[normalized_hash] = spec["sample_id"]
        sanitized_basis = "parsed_plain_text" if parsed else "raw_caption_fallback_after_parse_failure"
        sanitized_text, redactions = sanitize(parsed if parsed else raw_text)
        sanitized_path = REPORT_DIR / "sanitized" / f"{spec['sample_id']}.txt"
        sanitized_path.write_text(sanitized_text, encoding="utf-8")
        timeline = audit_timeline(raw_text)
        source_body = extract_source_body(raw_text)
        source_body_hash = hashlib.sha256(" ".join(source_body.casefold().split()).encode("utf-8")).hexdigest() if source_body else None
        source_body_duplicate_of = source_body_hashes.get((spec["identifier"], source_body_hash)) if source_body_hash else None
        if source_body_hash and not source_body_duplicate_of:
            source_body_hashes[(spec["identifier"], source_body_hash)] = spec["sample_id"]
        has_output_timestamp = bool(TIMESTAMP_RE.search(parsed))
        has_output_structure = bool(OUTPUT_METADATA_RE.search(parsed))
        license_url = license_record.get("licenseurl")
        source_page = license_record.get("source_page", f"https://archive.org/details/{spec['identifier']}")
        source_file_name = license_record.get("file_name", spec["file_name"])
        track_url = f"https://archive.org/download/{spec['identifier']}/{quote(source_file_name, safe='/')}"
        manifest_entries.append({
            "sample_id": spec["sample_id"],
            "platform": "Internet Archive",
            "source_id": spec["identifier"],
            "source_url": source_page,
            "caption_url_without_query": track_url,
            "captured_at_utc": receipt["captured_at_utc"],
            "collection_method": receipt["method"],
            "permission_basis": f"Item-level licenseurl {license_url}; reuse terms require attribution, source retained.",
            "license_url": license_url,
            "license_metadata_path": str(license_path.relative_to(REPORT_DIR)).replace("\\", "/"),
            "source_file_name": source_file_name,
            "original_format": ext,
            "sha256": raw_sha256,
            "archive_md5": receipt.get("archive_md5"),
            "bytes": len(raw_bytes),
            "capture_http_status": receipt.get("status_code"),
            "capture_http_elapsed_ms": receipt.get("elapsed_ms"),
            "collection_method": receipt.get("method"),
            "language": spec["language"],
            "language_basis": spec["language_basis"],
            "caption_origin": spec["caption_origin"],
            "title": license_record.get("title"),
            "raw_path": str(raw_path.relative_to(REPORT_DIR)).replace("\\", "/"),
            "sanitized_path": str(sanitized_path.relative_to(REPORT_DIR)).replace("\\", "/"),
            "sanitized_copy_basis": sanitized_basis,
        })
        result_entries.append({
            "sample_id": spec["sample_id"],
            "parser_pass": bool(parsed) and parser_error is None,
            "parser_error_type": parser_error,
            "sha256_matches_capture_receipt": byte_hash_matches_receipt,
            "utf8_strict_decode": utf8_strict,
            "decode_used": encoding,
            "unicode_replacement_character_count": raw_text.count("\ufffd"),
            "parsed_characters": len(parsed),
            "parsed_lines": len([line for line in parsed.splitlines() if line.strip()]),
            "nonempty_plain_text": bool(parsed.strip()),
            "timestamp_metadata_leaked_to_output": has_output_timestamp,
            "subtitle_structure_leaked_to_output": has_output_structure,
            "timeline_audit": timeline,
            "sanitized_copy_basis": sanitized_basis,
            "redactions": redactions,
            "normalized_content_duplicate_of": duplicate_of,
            "source_body_duplicate_of": source_body_duplicate_of,
            "source_body_comparison_available": bool(source_body),
            "exceeds_default_llm_input_limit_60000_chars": len(parsed) > 60000,
            "unmeasured": ["audio/text alignment", "speaker attribution accuracy", "background noise", "human linguistic quality review"],
        })

